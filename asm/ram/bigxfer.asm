; bigxfer.asm -- the serial settle test. RAM-resident: loaded, not burned.
;   load+run: make go-bigxfer        (asm/ram/bigxfer.asm -> RAM via L, then G)
;   soak:     python3 docs/notes/bigxfer_host.py --runs 5
;   check:    python3 docs/notes/test_bigxfer.py
;
; 2026-09-08, Rico: the fault is mechanical -- shifting the table changes
; it -- and 301 bytes loads consistently. Before the bench time goes to the
; PCB, one witness: a LARGE transfer, both directions, several times. This
; is it. About 2.2K goes IN through L (4400 characters, each echoed and
; checked, the sum witnessed by the monitor), then G runs it and it streams
; ITSELF back OUT: every byte from 0x8100 to its own end as two hex digits,
; 32 bytes a line, then one line
;
;     S hhll X xx
;
; with the 16-bit sum and the 8-bit xor of everything it read. The host
; compares the stream byte for byte against what it assembled, and the sums
; against its own. A wire that has settled passes this several times in a
; row; a wire that has not names the byte where it slipped.
;
; OB shows the pointer's HIGH byte while it streams, 0x81 up to 0x89: a
; stall names its page.
;
; The data is 2048 bytes from a seeded generator -- no structure, every
; value, so a stuck bit or a shifted nibble cannot hide. Code first, table
; after; the walk covers both, so the code bytes are read as data too.
;
; RAM: cells at 0x8000-0x800F. The monitor's 0x80E0-0x80FF is never touched.
; REGISTER DISCIPLINE, monitor.asm's rules: B is destroyed by every
; immediate-ALU op and by INR/DCR/SHL/NOT, so B is loaded right before each
; use; nothing lives in C across a CALL (RET's scratch).
; FIRST-OF-ITS-KIND: a RAM program reading its own code bytes as data
; through LDAX (life read only its tables); a 16-bit pointer walked across
; page boundaries 0x81..0x89 (every image so far kept its pointer in one
; page); JNC on ADD's carry to ripple a 16-bit sum (JNC has only ever
; followed SUB/CPI). Everything else is monitor idiom.

PUTHEX:   .equ  0x02C4          ; monitor.asm, `make listing-monitor`
PUTC:     .equ  0x0345
CRLF:     .equ  0x036B

PTRL:     .equ  0x8000          ; walk pointer
PTRH:     .equ  0x8001
CUR:      .equ  0x8002          ; the byte just read
S16L:     .equ  0x8003          ; 16-bit sum
S16H:     .equ  0x8004
XR:       .equ  0x8005          ; 8-bit xor
COL:      .equ  0x8006          ; bytes on this line

          .org  0x8100

start:    MVI   PTRL, <start
          MVI   PTRH, >start
          CLR
          STA   S16L
          STA   S16H
          STA   XR
          STA   COL

loop:     LDB   PTRH
          LDC   PTRL
          LDAX                  ; A = [PTR]
          STA   CUR
          LDB   PTRH
          MOVAB
          OUT                   ; progress: the page on OB

          LDB   CUR             ; S16 += CUR, carry into the high byte
          LDA   S16L
          ADD
          STA   S16L
          JNC   no_carry
          LDA   S16H
          INR
          STA   S16H
no_carry: LDB   CUR             ; XR ^= CUR
          LDA   XR
          XOR
          STA   XR

          LDA   CUR             ; print it
          CALL  PUTHEX
          LDA   COL             ; 32 to a line
          INR
          STA   COL
          CPI   32
          JNZ   no_crlf
          CALL  CRLF
          CLR
          STA   COL
no_crlf:  LDA   PTRL            ; PTR += 1
          INR
          STA   PTRL
          JNZ   check
          LDA   PTRH
          INR
          STA   PTRH
check:    LDA   PTRL            ; until PTR == end
          CPI   <end
          JNZ   loop
          LDA   PTRH
          CPI   >end
          JNZ   loop

          LDA   COL             ; end the last line if it is open
          CPI   0
          JNZ   tail_crlf
          JMP   report
tail_crlf: CALL CRLF
report:   LDAI  'S'
          CALL  PUTC
          LDAI  ' '
          CALL  PUTC
          LDA   S16H
          CALL  PUTHEX
          LDA   S16L
          CALL  PUTHEX
          LDAI  ' '
          CALL  PUTC
          LDAI  'X'
          CALL  PUTC
          LDAI  ' '
          CALL  PUTC
          LDA   XR
          CALL  PUTHEX
          CALL  CRLF
          RET

