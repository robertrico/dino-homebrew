"""The card registry: every card the FPGA twin can seat.

A card is KiCad-drawn (generated by fpga_card_gen.py from its project) or
hand-written RTL (fpga/cards/<name>.v). Either way it is a module on the
card contract (fpga_twin_gen.py docstring). Its entry says:

    kind      'kicad' or 'rtl'
    sch       the project's schematic (kicad)
    src       the Verilog file (rtl); the module is named after the card
    window    which '138 output its slot decode answers on: the 2K window
              0x4000 + 0x800 * window. For an rtl card it is also passed as
              the module's WINDOW parameter
    io_in     [(ref, pin, port)] off-edge stimulus nets (kicad): port_xo/_xe
    io_out    [(ref, pin, port)] off-edge probes (kicad)
    bind      {card port: dino_system expression} for the io ports
    outputs   {dino_system output: card port} driven by the card when seated
    oracle    read(offset, ctx) -> byte, the card as the oracle sees it
              (progrom_gen.simulate(cards=...)); None = not oracled

ADDING A CARD: write it to the contract (copy fpga/cards/proto_card.v),
add its entry here with its oracle model, and seat it with one line in
fpga_slots_gen.SLOTS. Nothing else. A drawn card is the same with kind
'kicad' and sch: draw it with a DINO_BUS_EDGE and fpga_card_gen.py makes
the module in fpga/gen/. Both kinds have the same ports; inside they differ
(fpga/README.md, "Two kinds of card, one API").
"""

DEADBEEF = {0x000: 0xDE, 0x555: 0xAD, 0x2AA: 0xBE, 0x7FF: 0xEF}


def _dip(offset, ctx):
    # a bare '244: all 2048 addresses in the window read SW1 (active low)
    return ctx.get('switches', 0xFF) & 0xFF


CARDS = {
    'dino_io': {
        'kind': 'kicad', 'sch': 'dino_io/dino_io.kicad_sch', 'window': 0,
        'io_in': [('SW1', str(i + 1), f'io_SW{i}') for i in range(8)],
        'io_out': [],
        'bind': {**{f'io_SW{i}_xo': "1'b0" for i in range(8)},
                 **{f'io_SW{i}_xe': f'sw_closed[{i}]' for i in range(8)}},
        'outputs': {},
        'oracle': _dip,
    },
    'dino_serial': {
        'kind': 'kicad', 'sch': 'dino_serial/dino_serial.kicad_sch', 'window': 1,
        'io_in': [('J1', '3', 'io_SIN')],          # FTDI header RX into SIN
        'io_out': [('J1', '4', 'io_SOUT')],        # SOUT out to the header
        'bind': {'io_SIN_xo': 'sin', 'io_SIN_xe': "1'b1"},
        'outputs': {'sout': 'io_SOUT'},
        # the UART is temporal; the oracle models it itself (simulate serial=)
        'oracle': None,
    },
    'proto_card': {
        'kind': 'rtl', 'src': 'fpga/cards/proto_card.v', 'window': 3,
        'io_in': [], 'io_out': [], 'bind': {}, 'outputs': {},
        'oracle': lambda offset, ctx: 0xFF,
    },
    'deadbeef_card': {
        'kind': 'rtl', 'src': 'fpga/cards/deadbeef_card.v', 'window': 2,
        'io_in': [], 'io_out': [], 'bind': {}, 'outputs': {},
        'oracle': lambda offset, ctx: DEADBEEF.get(offset, 0xFF),
    },
}

# what an undriven W reads: the bus-park pull-ups (progrom_gen.IO_PARK)
PARK = 0xFF


def oracle_cards(slots, ctx=None):
    """{window: read(addr)} for the oracle, from a slot table."""
    ctx = ctx or {}
    out = {}
    for slot, name in slots.items():
        c = CARDS[name]
        if c['oracle'] is None:
            continue
        if c['window'] in out:
            raise ValueError(f'two cards answer window {c["window"]} ({slot})')
        out[c['window']] = (lambda f: lambda addr: f(addr & 0x7FF, ctx))(c['oracle'])
    return out
