#!/usr/bin/env python3
"""The FPGA twin's backplane: the slot table -> fpga/gen/dino_system.v.

    python3 docs/notes/fpga_slots_gen.py [--seed N] [--half TICKS]

SLOTS below is the one slot table: which card sits in which of the
mainboard's sockets J1-J8. `generate()` runs every generator the table
needs (fpga_core_gen, fpga_card_gen for each KiCad card) and writes:

    dino_core.v          the mainboard, slots J1-J8 as contract ports
    <card>.v             each seated KiCad card
    dino_card_ports.vh   the card contract as a port list (rtl cards
                         include it)
    dino_card_in.vh      each edge pin as a card reads it (in_<signal>)
    dino_system.v        the backplane
    dino_system_files.txt  every Verilog file the system needs besides
                         fpga/ttl_fpga.v, absolute paths, in order
    dino_system_slots.txt  the slot table it was built from

The backplane joins each seated card to its slot by pin number, port for
port, through two wires per pin: to_jK_eP_S (core jK_eP_S_do/_de -> card
eP_S_xo/_xe) and from_jK_eP_S (card eP_S_do/_de -> core jK_eP_S_xo/_xe). An empty slot drives nothing (its _xe is 0). dino_system's
own ports are the machine's: clk, live, rc_low (hold the reset RC node
low), sw_closed (card zero's SW1), sin/sout (the serial card's line), ob,
halt, contention; a card's io ports bind to them by its registry entry.
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import fpga_card_gen  # noqa: E402
import fpga_cards  # noqa: E402
import fpga_core_gen  # noqa: E402
import fpga_twin_gen as g  # noqa: E402

# THE SLOT TABLE. A slot is a position, not an address: the card's own '138
# picks its window (fpga_cards.CARDS[...]['window']).
SLOTS = {
    'J1': 'dino_io',          # card 0: DIP switch, 0x4000
    'J2': 'dino_serial',      # card 1: 16550, 0x4800
    'J3': 'deadbeef_card',    # card 2: RTL, 0x5000
}

SYSTEM_OUTPUTS = {'sout': "1'b1"}     # an idle serial line with no card


def system(slots):
    """dino_system for a slot table."""
    for s in slots:
        assert s in fpga_core_gen.SLOTS, s
    windows = {}
    for s, name in slots.items():
        w = fpga_cards.CARDS[name]['window']
        if w in windows:
            raise ValueError(f'{s} and {windows[w]} both answer window {w}')
        windows[w] = s
    lines = ['// GENERATED by docs/notes/fpga_slots_gen.py: the mainboard and its slots.',
             '// ' + '  '.join(f'{s}={n}' for s, n in sorted(slots.items())),
             'module dino_system (input wire clk, live,',
             '  input wire rc_low,          // hold the reset RC node low (power-up, SW2)',
             '  input wire [7:0] sw_closed, // card zero SW1, 1 = switch closed',
             '  input wire sin,             // serial card SIN, from the host',
             '  output wire sout,           // serial card SOUT, to the host',
             '  output wire [7:0] ob, output wire halt, output wire contention);']
    core = ['.clk(clk)', '.live(live)', ".x_rc_node_xo(1'b0)", '.x_rc_node_xe(rc_low)',
            *[f'.p_OB{i}(ob[{i}])' for i in range(8)], '.p_HALT(halt)']
    cards, conts, outs = [], ['core_cont'], dict(SYSTEM_OUTPUTS)
    for slot in fpga_core_gen.SLOTS:
        k = slot.lower()
        name = slots.get(slot)
        for _pin, _n, stem in g.CONTRACT:
            sp = fpga_core_gen.slot_port(slot, stem)
            if name is None:
                core += [f".{sp}_xo(1'b0)", f".{sp}_xe(1'b0)"]
                continue
            lines.append(f'  wire to_{sp}_do, to_{sp}_de, from_{sp}_do, from_{sp}_de;')
            core += [f'.{sp}_xo(from_{sp}_do)', f'.{sp}_xe(from_{sp}_de)',
                     f'.{sp}_do(to_{sp}_do)', f'.{sp}_de(to_{sp}_de)']
        if name is None:
            continue
        c = fpga_cards.CARDS[name]
        conns = ['.clk(clk)', '.live(live)']
        for _pin, _n, stem in g.CONTRACT:
            sp = fpga_core_gen.slot_port(slot, stem)
            conns += [f'.{stem}_xo(to_{sp}_do)', f'.{stem}_xe(to_{sp}_de)',
                      f'.{stem}_do(from_{sp}_do)', f'.{stem}_de(from_{sp}_de)']
        conns += [f'.{p}({v})' for p, v in c['bind'].items()]
        for out, port in c['outputs'].items():
            if outs[out] != SYSTEM_OUTPUTS[out]:
                raise ValueError(f'two cards drive {out}')
            lines.append(f'  wire {k}_{port};')
            conns.append(f'.{port}({k}_{port})')
            outs[out] = f'{k}_{port}'
        lines.append(f'  wire {k}_cont;')
        conns.append(f'.contention({k}_cont)')
        conts.append(f'{k}_cont')
        ps = f'#(.WINDOW({c["window"]})) ' if c['kind'] == 'rtl' else ''
        cards.append(f'  {name} {ps}{k} (' + ', '.join(conns) + ');')
    lines.append('  wire core_cont;')
    lines.append('  dino_core core (' + ', '.join(core + ['.contention(core_cont)']) + ');')
    lines += cards
    for out, v in outs.items():
        lines.append(f'  assign {out} = {v};')
    lines.append(f'  assign contention = {" | ".join(conts)};')
    lines.append('endmodule')
    return '\n'.join(lines) + '\n'


def rtl_sources(slots):
    """Hand-written card files dino_system needs (repo-relative, unique)."""
    out = []
    for name in slots.values():
        c = fpga_cards.CARDS[name]
        if c['kind'] == 'rtl' and c['src'] not in out:
            out.append(c['src'])
    out += [s for s in CARD_LIBRARY if s not in out]
    return out


# shared by the hand-written cards
CARD_LIBRARY = ['fpga/cards/card_window.v']


def generate(seed=1, half=g.HALF, slots=None, out_dir=g.OUT_DIR):
    """Every generated file the twin needs, for one slot table."""
    slots = SLOTS if slots is None else slots
    os.makedirs(out_dir, exist_ok=True)
    info = {'core': fpga_core_gen.generate(seed, half, out_dir)}
    for name in sorted(set(slots.values())):
        if fpga_cards.CARDS[name]['kind'] == 'kicad':
            info[name] = fpga_card_gen.generate(name, seed, half, out_dir)
    open(os.path.join(out_dir, 'dino_card_ports.vh'), 'w').write(g.card_ports_vh())
    open(os.path.join(out_dir, 'dino_card_in.vh'), 'w').write(g.card_in_vh())
    open(os.path.join(out_dir, 'dino_system.v'), 'w').write(system(slots))
    files = [os.path.join(out_dir, f'{n}.v') for n in ['dino_core'] + sorted(
        n for n in set(slots.values()) if fpga_cards.CARDS[n]['kind'] == 'kicad')]
    files += [os.path.join(g.ROOT, s) for s in rtl_sources(slots)]
    files.append(os.path.join(out_dir, 'dino_system.v'))
    info['files'] = files
    open(os.path.join(out_dir, 'dino_system_files.txt'), 'w').write('\n'.join(files) + '\n')
    open(os.path.join(out_dir, 'dino_system_slots.txt'), 'w').write(
        ''.join(f'{s} {n}\n' for s, n in sorted(slots.items())))
    return info


def main(argv):
    seed = int(argv[argv.index('--seed') + 1]) if '--seed' in argv else 1
    half = int(argv[argv.index('--half') + 1]) if '--half' in argv else g.HALF
    info = generate(seed, half)
    for k, v in info.items():
        if k != 'files':
            print(f'{k}: {len(v["chips"])} chips')
    print('slots: ' + '  '.join(f'{s}={n}' for s, n in sorted(SLOTS.items())))


if __name__ == '__main__':
    main(sys.argv[1:])
